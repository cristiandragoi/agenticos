/* ── Budgets (evidence protection) ─────────────────────────────── */
export const WI_MAX_RESULTS = 25;
export const WI_MAX_SNIPPET_CHARS = 240;
export const WI_MAX_AGGREGATE_CHARS = 8000;
export const WI_MAX_FILE_SIZE = 512 * 1024; // per-file indexing cap
export const WI_SEARCH_TIMEOUT_MS = 5000;
export const WI_MAX_FILES_SCANNED = 60000;
export const WI_MAX_SYMBOLS = 50;

/* ── Ignore policy (P4) ────────────────────────────────────────── */
const IGNORE_DIRS = new Set([
  'node_modules', '.git', 'dist', 'dist-electron', 'build', '.agentos',
  '.agentic', '.hermes', '.claude', 'coverage', '.venv', 'venv',
  '__pycache__', '.cache', '.turbo', 'target', '.next', '.nuxt', 'out',
  '.parcel-cache', '.serverless', '.idea', '.vscode', '.docusaurus',
  'release', 'tmp', '.tmp',
]);
const IGNORE_FILE_PATTERNS = [
  /^\.env(\..*)?$/, /^\.env$/, /^\.DS_Store$/, /^Thumbs\.db$/,
  /^package-lock\.json$/, /^yarn\.lock$/, /^pnpm-lock\.(yaml|yml)$/,
  /^npm-shrinkwrap\.json$/, /^\.eslintcache$/, /^tsconfig\.tsbuildinfo$/,
  /^.*\.(pem|key|p12|pfx|crt|pub)$/i, /^credentials.*$/i, /^secrets.*$/i,
  /^.*_key\.json$/i,
];
const IGNORE_EXT = new Set([
  '.db', '.sqlite', '.sqlite3', '.map', '.lock', '.min.js', '.bundle.js',
  '.png', '.jpg', '.jpeg', '.gif', '.webp', '.ico', '.svg', '.woff',
  '.woff2', '.ttf', '.eot', '.pdf', '.zip', '.gz', '.tar', '.7z', '.rar',
  '.exe', '.dll', '.so', '.dylib', '.class', '.jar', '.pyc', '.mp3',
  '.mp4', '.wav', '.mov', '.avi', '.wasm', '.node', '.obj', '.o', '.a',
  '.bin', '.dat', '.log', '.tsbuildinfo',
]);
