/**
 * WorkspaceIndexer V1 — bounded, project-scoped evidence retrieval.
 *
 * Architecture (per docs/proposals/workspace-indexer-audit.md):
 *   - Local-first, deterministic, model-independent.
 *   - SQLite FTS5 for ranked TEXT retrieval (same proven pattern as
 *     memory_fts in services/memory/store.ts).
 *   - Live in-process literal scan for EXACT mode (zero-staleness,
 *     authoritative ground truth — no shell-outs, no findstr/grep).
 *   - No embeddings, no AST, no vector DB (audit §3).
 *
 * Security contract:
 *   - The authoritative workspace root comes from workspaceStore
 *     (getWorkspaceRoot / project.workspacePath) — never from arbitrary
 *     API input.
 *   - Every scanned path is verified inside the workspace root
 *     (isPathInsideWorkspace).
 *   - Ignore rules exclude node_modules/.git/dist/build/runtime data/
 *     secret files/binaries; nothing outside the workspace is touched.
 *   - Indexing is local filesystem processing only — zero cloud-model
 *     calls are generated by indexing or search (privacy-policy aware by
 *     construction; P16 proves it at runtime).
 */
